import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { type Package } from 'custom-elements-manifest' with { type: 'json' };

/**
 * Writes types for using Slab's elements in JSX and framework templates, so a
 * misspelled attribute or a wrong value is a type error rather than a silent
 * no-op:
 *
 * - `dist/jsx.d.ts`: `SlabElementProps`, each tag's settable properties, for
 *   any framework to build on.
 * - `dist/react.d.ts`, `dist/svelte.d.ts` and `dist/vue.d.ts`: each adds the
 *   tags to its framework's own list of elements once it's imported with
 *   `import type {} from 'slab-elements/react.js'`, or Svelte or Vue's.
 *
 * Each tag's properties are picked from its class rather than written out, so
 * they're exactly the class's types: every public property that isn't
 * read-only, which includes every attribute's. Each framework module has an
 * empty JavaScript twin, because `exports` maps each `.js` path to both.
 */
export default () => {
  return {
    name: 'write-jsx-types',
    packageLinkPhase({
      customElementsManifest,
    }: {
      customElementsManifest: Package;
    }) {
      const imports: string[] = [];
      const entries: string[] = [];

      for (const module of customElementsManifest.modules) {
        for (const declaration of module.declarations ?? []) {
          if (
            !('customElement' in declaration) ||
            !declaration.customElement ||
            !('tagName' in declaration) ||
            !declaration.tagName
          ) {
            continue;
          }

          const isDefault = module.exports?.some((exported) => {
            return (
              exported.kind === 'js' &&
              exported.name === 'default' &&
              exported.declaration.name === declaration.name
            );
          });

          // Only a module's default export is importable as a class here.
          if (!isDefault) {
            continue;
          }

          const names = (declaration.members ?? [])
            .filter((member) => {
              return (
                member.kind === 'field' &&
                !member.readonly &&
                !member.static &&
                member.privacy !== 'private' &&
                member.privacy !== 'protected'
              );
            })
            .map(({ name }) => `'${name}'`)
            .sort();

          const file = `./${path.basename(module.path, '.ts')}.js`;
          const alias = `${declaration.name}${imports.length}`;

          imports.push(`import type ${alias} from '${file}';`);

          entries.push(
            `  '${declaration.tagName}': Partial<Pick<${alias}, ${names.length > 0 ? names.join(' | ') : 'never'}>>;`,
          );
        }
      }

      const jsx = `// Generated by \`src/cem-analyzer-plugins/write-jsx-types.ts\`.
${imports.join('\n')}

/**
 * Each of Slab's tags, and the properties it can be given: every public one
 * that isn't read-only. Its attributes are among them, by property name.
 */
export interface SlabElementProps {
${entries.join('\n')}
}
`;

      const react = `// Generated by \`src/cem-analyzer-plugins/write-jsx-types.ts\`.
//
// Adds Slab's tags to React's JSX: \`import type {} from 'slab-elements/react.js';\`
// React 19 sets a prop as a property when the element has one, so these are
// property names, such as \`hideLabel\`.
import type { DetailedHTMLProps, HTMLAttributes } from 'react';
import type { SlabElementProps } from './jsx.js';

type SlabReactElements = {
  [Tag in keyof SlabElementProps]: Omit<
    DetailedHTMLProps<
      HTMLAttributes<HTMLElementTagNameMap[Tag]>,
      HTMLElementTagNameMap[Tag]
    >,
    keyof SlabElementProps[Tag]
  > &
    SlabElementProps[Tag] & { class?: string };
};

declare module 'react' {
  namespace JSX {
    interface IntrinsicElements extends SlabReactElements {}
  }
}
`;

      const svelte = `// Generated by \`src/cem-analyzer-plugins/write-jsx-types.ts\`.
//
// Adds Slab's tags to Svelte 5's elements: \`import type {} from 'slab-elements/svelte.js';\`
import type { HTMLAttributes } from 'svelte/elements';
import type { SlabElementProps } from './jsx.js';

type SlabSvelteElements = {
  [Tag in keyof SlabElementProps]: Omit<
    HTMLAttributes<HTMLElementTagNameMap[Tag]>,
    keyof SlabElementProps[Tag]
  > &
    SlabElementProps[Tag];
};

declare module 'svelte/elements' {
  interface SvelteHTMLElements extends SlabSvelteElements {}
}
`;

      const vue = `// Generated by \`src/cem-analyzer-plugins/write-jsx-types.ts\`.
//
// Adds Slab's tags to Vue's templates: \`import type {} from 'slab-elements/vue.js';\`
// Vue still needs \`isCustomElement\` in its compiler options to leave them
// to the browser.
import type { DefineComponent } from 'vue';
import type { SlabElementProps } from './jsx.js';

type SlabVueElements = {
  [Tag in keyof SlabElementProps]: DefineComponent<SlabElementProps[Tag]>;
};

declare module 'vue' {
  interface GlobalComponents extends SlabVueElements {}
}
`;

      mkdirSync('./dist', { recursive: true });

      for (const [name, types] of Object.entries({ jsx, react, svelte, vue })) {
        writeFileSync(`./dist/${name}.d.ts`, types);
        writeFileSync(`./dist/${name}.js`, 'export {};\n');
      }
    },
  };
};
